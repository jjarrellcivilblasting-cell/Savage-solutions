try {
  const saved = localStorage.getItem(STORAGE_KEY);
  language = saved === 'en' || saved === 'es' ? saved :
    (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
} catch { language = (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en'; }
const originalText = new WeakMap();
const originalAttrs = new WeakMap();
const supportedAttrs = ['placeholder','aria-label','title'];
const replacements = [
  [/^(.+) is required\\.$/, m => localize(m[1]) + ' es obligatorio.'],
  [/^(.+) must be (a whole number|a number) (greater than zero|from ([0-9.]+)) and at most ([0-9.]+)\\.$/, m => localize(m[1]) + ' debe ser ' + (m[2]==='a whole number'?'un número entero':'un número') + (m[3]==='greater than zero'?' mayor que cero':' desde '+m[4]) + ' y como máximo ' + m[5] + '.'],
  [/^([0-9,.]+) bd ft( \\(Doyle estimate\\))?$/, m => m[1] + ' pies tablares' + (m[2]?' (estimación Doyle)':'')],
  [/^([0-9,.]+) (yd³|ft²|ft² to order|% grade|US gallons|short tons|meters)$/, m => m[1] + ' ' + localize(m[2])],

  [/^(\d+) calculators? available across all trades\. More tools will be added\.$/, m => m[1] + ' calculadoras disponibles para todos los oficios. Se añadirán más herramientas.'],
  [/^(\d+) calculators? available for (.+)\. More tools will be added\.$/, m => m[1] + ' calculadoras disponibles para ' + localize(m[2]) + '. Se añadirán más herramientas.'],
  [/^Job #(\d+) submitted for moderation\. It is NOT publicly listed until approved\.$/, m => 'Trabajo n.º ' + m[1] + ' enviado a revisión. NO se publicará hasta que sea aprobado.'],
  [/^Feedback #(\d+) received\. Thank you\.$/, m => 'Comentarios n.º ' + m[1] + ' recibidos. Gracias.'],
  [/^(\d+(?:\.\d+)?) man-hours \/ (.+)$/, m => m[1] + ' horas-hombre / ' + m[2]],
  [/^(.+) cost \/ (.+) quote \/ (.+) profit$/, m => m[1] + ' costo / ' + m[2] + ' presupuesto / ' + m[3] + ' ganancia'],
  [/^Status: (Complete|In progress)$/, m => 'Estado: ' + localize(m[1])],
  [/^Saved (.+)$/, m => 'Guardado: ' + m[1]],
  [/^Budget: (.+)$/, m => 'Presupuesto: ' + m[1]],
  [/^Deadline: (.+)$/, m => 'Fecha límite: ' + m[1]],
  [/^Edit (.+)$/, m => 'Editar ' + m[1]],
  [/^Delete (.+)$/, m => 'Eliminar ' + m[1]],
  [/^([^\n]+) — (.+)$/, m => m[1] + ' — ' + localize(m[2])]
];
export function getLanguage() { return language; }
export function localize(source) {
  if (language !== 'es' || typeof source !== 'string') return source;
  if (Object.hasOwn(es, source)) return es[source];
  for (const [re, handler] of replacements) {
    const m = source.match(re);
    if (m) return handler(m);
  }
  return source;
}
export function localizeMessage(source) {
  if (typeof source !== 'string') return source;
  const trimmed=source.trim();
  if (!trimmed) return source;
  return source.replace(trimmed, localize(trimmed));
}
function skipNode(node) {
  const el = node.nodeType === 1 ? node : node.parentElement;
  return !el || !!el.closest('script,style,template,[data-no-translate]');
}
function translateTextNode(node) {
  if(skipNode(node)) return;
  const current=node.nodeValue;
  let state=originalText.get(node);
  if(!state || (current!==state.rendered && current!==state.source)){
    state={source:current,rendered:current};originalText.set(node,state);
  }
  const next=localizeMessage(state.source);
  state.rendered=next;
  if(current!==next)node.nodeValue=next;
}
function translateAttr(element,name) {
  if(skipNode(element)||!element.hasAttribute(name))return;
  let values=originalAttrs.get(element);
  if(!values){values=new Map();originalAttrs.set(element,values);}
  const current=element.getAttribute(name);
  let state=values.get(name);
  if(!state || (current!==state.rendered&&current!==state.source)){
    state={source:current,rendered:current};values.set(name,state);
  }
  const next=localizeMessage(state.source);
  state.rendered=next;
  if(current!==next)element.setAttribute(name,next);
}
function translateTree(node) {
  if(node.nodeType===3)return translateTextNode(node);
  if(node.nodeType!==1||skipNode(node))return;
  for(const attr of supportedAttrs)translateAttr(node,attr);
  for(const child of node.childNodes)translateTree(child);
}
function applyLanguage() {
  document.documentElement.lang=language;
  document.title=language==='es'?spanishTitle:englishTitle;
  const selector=document.getElementById('languageSelect');
  if(selector)selector.value=language;
  translateTree(document.body);
}
export function setLanguage(next) {
  if(next!=='en'&&next!=='es')return;
  language=next;
  try{localStorage.setItem(STORAGE_KEY,next);}catch{}
  applyLanguage();
  window.dispatchEvent(new CustomEvent('savage-language-changed',{detail:{language:next}}));
}
export function onLanguageChange(callback){
  window.addEventListener('savage-language-changed',callback);
}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',applyLanguage,{once:true});
else applyLanguage();
document.getElementById('languageSelect')?.addEventListener('change',event=>setLanguage(event.target.value));
const observer=new MutationObserver(mutations=>{
  for(const change of mutations){
    if(change.type==='characterData')translateTextNode(change.target);
    if(change.type==='childList')for(const child of change.addedNodes)translateTree(child);
    if(change.type==='attributes'&&supportedAttrs.includes(change.attributeName))translateAttr(change.target,change.attributeName);
  }
});
observer.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:supportedAttrs});
